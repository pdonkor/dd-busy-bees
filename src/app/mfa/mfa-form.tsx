"use client";

import { useRouter } from "next/navigation";
import { useEffect, useState } from "react";
import { Alert, Button, Field, Input } from "@/components/ui";
import { createClient } from "@/lib/supabase/client";

type Setup = { factorId: string; qrCode?: string; secret?: string };

export function MfaForm() {
  const router = useRouter();
  const [setup, setSetup] = useState<Setup | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const supabase = createClient();
    (async () => {
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (error) return setError("Could not load your verification settings. Please reload.");
      const verified = data.totp.find((f) => f.status === "verified");
      if (verified) return setSetup({ factorId: verified.id });

      // First time: remove any half-finished enrolment, then start a new one.
      for (const f of data.all.filter((f) => f.status === "unverified")) {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const enrolled = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "Authenticator app" });
      if (enrolled.error) return setError("Could not start set-up. Please reload.");
      setSetup({ factorId: enrolled.data.id, qrCode: enrolled.data.totp.qr_code, secret: enrolled.data.totp.secret });
    })();
  }, []);

  async function verify(formData: FormData) {
    if (!setup) return;
    setBusy(true);
    setError(null);
    const code = String(formData.get("code") ?? "").replace(/\s/g, "");
    const { error } = await createClient().auth.mfa.challengeAndVerify({ factorId: setup.factorId, code });
    setBusy(false);
    if (error) return setError("That code didn't work. Check your app and try the newest code.");
    router.replace("/owner");
    router.refresh();
  }

  if (!setup) return error ? <Alert>{error}</Alert> : <p className="text-sm text-stone-600">Loading…</p>;

  return (
    <form action={verify} className="space-y-4">
      {setup.qrCode && (
        <div className="space-y-2 text-sm text-stone-700">
          <p>Scan this with Google Authenticator, Microsoft Authenticator or Authy, then enter the 6-digit code.</p>
          {/* eslint-disable-next-line @next/next/no-img-element -- data URI generated by Supabase */}
          <img src={setup.qrCode} alt="QR code for your authenticator app" className="mx-auto h-48 w-48" />
          <p className="break-all text-xs text-stone-500">Can&apos;t scan? Enter this key: {setup.secret}</p>
        </div>
      )}
      {error && <Alert>{error}</Alert>}
      <Field label="Code from your authenticator app">
        <Input name="code" inputMode="numeric" autoComplete="one-time-code" maxLength={7} required autoFocus />
      </Field>
      <Button type="submit" disabled={busy}>
        {busy ? "Checking…" : "Verify"}
      </Button>
    </form>
  );
}
